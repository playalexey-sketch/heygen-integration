def wrap(text: str, width: int) -> list[str]:
    return textwrap.wrap(text, width=width, break_long_words=False, break_on_hyphens=False) or [""]


def annotation_args(text: str, x: int, y: int, size: int, color: str, font: str, width: int = 48, line_height: float = 1.28) -> tuple[list[str], int]:
    lines = []
    for paragraph in str(text).split("\n"):
        lines.extend(wrap(paragraph, width))
    rendered = "\n".join(lines)
    args = ["-stroke", "none", "-font", font, "-pointsize", str(size), "-fill", color, "-interline-spacing", str(int(size * (line_height - 1))), "-annotate", f"+{x}+{y}", rendered]
    used = int(len(lines) * size * line_height)
    return args, used


def run_convert(args: list[str]) -> None:
    subprocess.run(["convert", *args], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


