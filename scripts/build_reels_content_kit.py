def jpeg_dimensions(data: bytes) -> tuple[int, int]:
    i = 2
    while i < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        i += 2
        if marker in (0xD8, 0xD9):
            continue
        length = int.from_bytes(data[i:i+2], "big")
        if marker in range(0xC0, 0xC4):
            h = int.from_bytes(data[i+3:i+5], "big")
            w = int.from_bytes(data[i+5:i+7], "big")
            return w, h
        i += length
    return W, H


def write_image_pdf(images: list[Path], output: Path) -> None:
    objects: list[bytes | None] = [None, None]
    page_refs: list[int] = []
    for image_path in images:
        data = image_path.read_bytes()
        iw, ih = jpeg_dimensions(data)
        page_num = len(objects) + 1
        content_num = page_num + 1
        image_num = page_num + 2
        page_refs.append(page_num)
        page_obj = f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {A4_W:.3f} {A4_H:.3f}] /Resources << /XObject << /Im0 {image_num} 0 R >> >> /Contents {content_num} 0 R >>".encode()
        stream = f"q {A4_W:.3f} 0 0 {A4_H:.3f} 0 0 cm /Im0 Do Q".encode()
        content_obj = b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream"
        image_obj = (f"<< /Type /XObject /Subtype /Image /Width {iw} /Height {ih} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length {len(data)} >>\nstream\n".encode() + data + b"\nendstream")
        objects.extend([page_obj, content_obj, image_obj])
    objects[0] = b"<< /Type /Catalog /Pages 2 0 R >>"
    kids = " ".join(f"{ref} 0 R" for ref in page_refs)
    objects[1] = f"<< /Type /Pages /Kids [{kids}] /Count {len(page_refs)} >>".encode()
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for n, obj in enumerate(objects, 1):
        offsets.append(len(out))
        out.extend(f"{n} 0 obj\n".encode())
        out.extend(obj or b"")
        out.extend(b"\nendobj\n")
    xref = len(out)
    out.extend(f"xref\n0 {len(objects)+1}\n".encode())
    out.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        out.extend(f"{offset:010d} 00000 n \n".encode())
    out.extend(f"trailer\n<< /Size {len(objects)+1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    output.write_bytes(out)


def document_markdown(doc: dict[str, Any], label: str) -> str:
    lines = [f"# {doc['title']}", "", f"**{doc['subtitle']}**", "", f"> {doc.get('promise', doc.get('source', ''))}", ""]
    for title, items in doc["sections"]:
        lines += [f"## {title}", ""]
        lines += [f"- {item}" for item in items]
        lines.append("")
    if doc.get("offer"):
        lines += ["## Следующий шаг", "", f"> {doc['offer']}", ""]
    return "\n".join(lines)


def inline_md(text: str) -> str:
    value = html.escape(text)
