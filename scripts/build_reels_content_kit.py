def chunk_section(title: str, items: list[str], max_units: int = 25) -> list[tuple[str, list[str]]]:
    chunks: list[tuple[str, list[str]]] = []
    current: list[str] = []
    units = 0
    for item in items:
        item_units = max(2, math.ceil(len(item) / 68) + 1)
        if current and units + item_units > max_units:
            chunks.append((title if not chunks else f"{title} · продолжение", current))
            current, units = [], 0
        current.append(item)
        units += item_units
    if current:
        chunks.append((title if not chunks else f"{title} · продолжение", current))
    return chunks


