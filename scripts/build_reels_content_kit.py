def build_document_set(documents: list[dict[str, Any]], label: str, pdf_folder: Path, source_folder: Path) -> list[Path]:
    pdfs = []
    for doc in documents:
        page_dir = PAGES / label.lower().replace(" ", "_") / doc["slug"]
        pages = build_pages(doc, label, page_dir)
        pdf_path = pdf_folder / f"{doc['number']}_{doc['slug']}.pdf"
        write_image_pdf(pages, pdf_path)
        pdfs.append(pdf_path)
        md_path = source_folder / f"{doc['number']}_{doc['slug']}.md"
        html_path = source_folder / f"{doc['number']}_{doc['slug']}.html"
        md_path.write_text(document_markdown(doc, label), encoding="utf-8")
        html_path.write_text(document_html(doc, label), encoding="utf-8")
    return pdfs


def render_shot_map(path: Path, shot: dict[str, Any]) -> None:
    args = ["-size", f"{W}x{H}", f"xc:{COLORS['espresso']}"]
    gap = 5
    cell_w = (W - 2 * gap) // 3
    cell_h = (H - 2 * gap) // 3
    for idx, (label, duration, visual, text) in enumerate(shot["frames"]):
        row, col = divmod(idx, 3)
        x, y = col * (cell_w + gap), row * (cell_h + gap)
        fill = COLORS["espresso2"] if "A-ROLL" in label or "HOOK" in label else "#2F2A26"
        if "CTA" in label:
            fill = "#4A3C33"
        args += ["-fill", fill, "-draw", f"rectangle {x},{y} {x+cell_w},{y+cell_h}"]
        args += ["-stroke", COLORS["gold"], "-strokewidth", "1", "-draw", f"line {x+22},{y+88} {x+22},{y+140}"]
        a, _ = annotation_args(f"{idx+1}/9  {label}", x+18, y+28, 12, COLORS["cream2"], FONT_SANS_BOLD, 24)
        args += a
        a, _ = annotation_args(duration, x+cell_w-65, y+28, 11, COLORS["cream2"], FONT_SANS, 8)
        args += a
        a, vu = annotation_args(visual, x+34, y+115, 18, COLORS["gold2"], FONT_SERIF, 22, 1.2)
        args += a
        a, _ = annotation_args(text, x+26, y+cell_h-100, 16, COLORS["white"], FONT_SANS, 23, 1.22)
        args += a
    args += ["-quality", "86", str(path)]
    run_convert(args)


def build_shot_maps() -> Path:
    page_dir = PAGES / "shot_maps"
